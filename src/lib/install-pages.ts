const LANGS = ["az", "en", "tr", "ar", "ru"] as const;

function page(
  slug: string,
  name: string,
  title: Record<Lang, string>,
  description: Record<Lang, string>,
  keywords: Record<Lang, string>,
  version: Record<Lang, string>,
  steps: Record<Lang, readonly string[]>,
  expect: Record<Lang, string>,
  code: string,
  diff: Record<Lang, string>,
): StackPage {
  const heads = {
    version: t("Bu gün qurulacaq versiya", "Version to install", "Bugün kurulacak sürüm", "الإصدار الذي يُثبَّت اليوم", "Версия для установки"),
    steps: t("Windows-da addımlar", "Steps on Windows", "Windows adımları", "خطوات على Windows", "Шаги в Windows"),
    check: t("Yoxlama", "Check", "Kontrol", "التحقق", "Проверка"),
    old: t("Köhnə versiya ilə fərq", "Difference from the old version", "Eski sürümle fark", "الفرق عن الإصدار القديم", "Разница со старой версией"),
  };
  const checked = t(
    "Yoxlanılıb: 20 oktyabr 2026.",
    "Checked: 20 October 2026.",
    "Kontrol: 20 Ekim 2026.",
    "فُحص في 20 أكتوبر 2026.",
    "Проверено: 20 октября 2026.",
  );
  const sections = {} as Record<Lang, ProgrammingSection[]>;
  for (const lang of LANGS) {
    sections[lang] = [
      { id: "version", title: heads.version[lang], blocks: [{ paragraphs: [version[lang], checked[lang]] }] },
      { id: "steps", title: heads.steps[lang], blocks: [{ list: steps[lang], ordered: true }] },
      { id: "check", title: heads.check[lang], blocks: [{ paragraphs: [expect[lang]], code }] },
      { id: "old", title: heads.old[lang], blocks: [{ paragraphs: [diff[lang]] }] },
    ];
  }
  return { slug, name, title, description, keywords, sections };
}

