const STOP = new Set(["the","a","an","and","or","of","to","in","for","with","on","ve","ile","bir","i","v","s","na","za","al","wa"]);
function slugify(s) {
  s = s.toLowerCase().split(/[—–:|(]/)[0] + " " + (s.split(/[—–]/)[1] ?? "");
  s = [...s].map((c) => RU[c] ?? AR[c] ?? LAT[c] ?? c).join("").normalize("NFKD").replace(/[\u0300-\u036f\u064b-\u065f]/g, "");
  const w = s.replace(/[^a-z0-9]+/g, " ").trim().split(" ").filter((x) => x && !STOP.has(x));
  let out = ""; for (const x of w) { if ((out + "-" + x).length > 48) break; out = out ? out + "-" + x : x; }
  return out;
}
const out = {};
function add(sec, items) {
  const m = (out[sec] = {}); const used = { en: new Set(), tr: new Set(), ar: new Set(), ru: new Set() };
  for (const it of items) {
    if (m[it.slug]) continue;
    const e = {};
    for (const l of ["en", "tr", "ar", "ru"]) {
      const t = it.piece?.[l]?.title ?? it.title?.[l] ?? it.label?.[l];
      let s = t ? slugify(t) : "";
      if (!s || s.length < 3) s = it.slug;
      while (used[l].has(s)) s += "-2";
      used[l].add(s); e[l] = s;
    }
    m[it.slug] = e;
  }
}
