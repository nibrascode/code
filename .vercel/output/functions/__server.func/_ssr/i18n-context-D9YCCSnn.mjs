function readLang(searchStr) {
	const raw = new URLSearchParams((searchStr ?? "").replace(/^\?/, "")).get("lang");
	if (raw === "en" || raw === "ar" || raw === "ru" || raw === "az" || raw === "tr") return raw;
	return "az";
}
