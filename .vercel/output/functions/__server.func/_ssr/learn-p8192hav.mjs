/** The answer is checked against the source sentence itself, not only the stored index. */
function isCorrect(card, picked) {
	const norm = (s) => s.trim().toLocaleLowerCase();
	return norm(picked) === norm(card.word) && card.source.toLocaleLowerCase().includes(norm(picked));
}
function grade(card, ok, now = Date.now()) {
	const box = ok ? Math.min(5, card.box + 1) : 0;
	return {
		...card,
		box,
		due: ok ? now + GAPS[box] * DAY : now,
		right: card.right + (ok ? 1 : 0),
		wrong: card.wrong + (ok ? 0 : 1),
		seen: card.seen + 1
	};
}
