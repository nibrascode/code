/** Split page texts into topic sections: by detected headings, or by page groups when none. */
function buildSections(pages, fallbackTitle) {
	const lines = [];
	pages.forEach((p, i) => p.split(/\n/).forEach((text) => lines.push({
		text,
		page: i + 1
	})));
	const heads = lines.filter((l) => isHeading(l.text)).length;
	const out = [];
	const push = (title, rows) => {
		let text = "";
		const pageStarts = [];
		for (const r of rows) {
			if (!pageStarts.length || pageStarts[pageStarts.length - 1].page !== r.page) pageStarts.push({
				at: text.length,
				page: r.page
			});
			text += (text && !/-$/.test(text) ? " " : "") + r.text.trim();
		}
		if ((text.match(/\S+/g) ?? []).length >= 25) out.push({
			id: uid(),
			title: title.slice(0, 80),
			text,
			pageStarts
		});
	};
	if (heads >= 2 && heads <= 60) {
		let title = "";
		let rows = [];
		for (const l of lines) if (isHeading(l.text)) {
			if (rows.length) push(title || fallbackTitle(rows[0].page, rows[rows.length - 1].page), rows);
			title = l.text.trim();
			rows = [];
		} else rows.push(l);
		if (rows.length) push(title || fallbackTitle(rows[0].page, rows[rows.length - 1].page), rows);
	}
	if (out.length < 2) {
		out.length = 0;
		const per = Math.max(1, Math.ceil(pages.length / 8));
		for (let i = 0; i < pages.length; i += per) {
			const rows = lines.filter((l) => l.page > i && l.page <= i + per);
			push(fallbackTitle(i + 1, Math.min(pages.length, i + per)), rows);
		}
	}
	return out;
}
