function make(app, rows) {
	return rows.map(([cat, desc, win, mac], i) => ({
		id: `${app}-${i}`,
		app,
		cat,
		desc,
		...win ? { win } : {},
		...mac === null ? {} : { mac: mac ?? (win ? auto(win) : void 0) }
	}));
}
